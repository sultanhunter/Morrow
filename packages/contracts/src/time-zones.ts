const zoneSet: ReadonlySet<string> = new Set(ianaTimeZones);
/** Whether a value is a zone of the closed list, exactly. */
export function isIanaTimeZone(value: unknown): value is string {
  return typeof value === "string" && zoneSet.has(value);
}
/**
 * The zone of the closed list a name stands for: the name itself, or the zone of one of Intl's
 * aliases; null for anything else (an unknown or malformed name is never guessed at).
 */
export function canonicalTimeZone(value: unknown): string | null {
  if (typeof value !== "string") return null;
  if (zoneSet.has(value)) return value;
  return Object.hasOwn(ianaTimeZoneAliases, value) ? ianaTimeZoneAliases[value]! : null;
}
